// Categories the old dashboard summed as "Fixos".
var fixedCategories = map[string]bool{"Condomínio": true, "Financiamento": true, "Luz": true, "Gás": true, "Internet": true, "MEI": true}

func bucketFor(name string) finance.Bucket {
	switch {
	case name == "Fatura cartão":
		return finance.Card
	case fixedCategories[name]:
		return finance.Fixed
	}
	return finance.Other
}

// legacyPayment maps the old dashboard group of an expense category to the
// payment method and fixed flag of its transactions, like migration 0007.
func legacyPayment(kind finance.Kind, b finance.Bucket) (finance.PaymentMethod, bool) {
	if kind != finance.Expense {
		return finance.OtherPay, false
	}
	if b == finance.Card {
		return finance.Credit, false
	}
	return finance.OtherPay, b == finance.Fixed
}

type row struct {
	kind   finance.Kind
	date   time.Time
	amount int64
	cat    string
	note   string
	auto   bool // generated by the spreadsheet ("fixo automático")
}

type importer struct {
	st     *db.Store
	today  time.Time
	out    io.Writer
	catIDs map[string]int64 // kind|name → id
}

func (im *importer) cat(kind finance.Kind, name string) (int64, error) {
	key := string(kind) + "|" + name
	if id, ok := im.catIDs[key]; ok {
		return id, nil
	}
	id, err := im.st.EnsureCategory(name, kind)
	if err == nil {
		im.catIDs[key] = id
	}
	return id, err
}

// Run imports the spreadsheet into an empty database and prints a
// month-by-month comparison against the spreadsheet's own dashboard.
func Run(st *db.Store, file string, today time.Time, out io.Writer) error {
	sheets, err := readWorkbook(file)
	if err != nil {
		return err
	}
	need := func(name string) (Sheet, error) {
		s, ok := sheets[name]
		if !ok {
			return nil, fmt.Errorf("aba %q não encontrada", name)
		}
		return s, nil
	}
	im := &importer{st: st, today: finance.DateOnly(today), out: out, catIDs: map[string]int64{}}
	cur := finance.MonthOf(im.today)

	// --- settings
	if dash, ok := sheets["Dashboard"]; ok {
		if v, ok := cents(dash.Get("B5")); ok {
			st.SetSettingInt("card_limit_cents", v)
		}
		if v, ok := cents(dash.Get("B6")); ok {
			st.SetSettingInt("min_savings_cents", v)
		}
	}

	// --- categories from Config
	if cfg, ok := sheets["Config"]; ok {
		for r := 5; r < 200; r++ {
			if v := strings.TrimSpace(cfg[r]["D"]); v != "" {
				if _, err := im.cat(finance.Expense, v); err != nil {
					return err
				}
			}
			if v := strings.TrimSpace(cfg[r]["F"]); v != "" {
				if _, err := im.cat(finance.Income, v); err != nil {
					return err
				}
			}
		}
	}

	// --- debts
	debtIDs := map[string]int64{}
	if dv, ok := sheets["Dívidas"]; ok {
		for r := 2; r < 100; r++ {
			name := strings.TrimSpace(dv[r]["A"])
			amt, ok := cents(dv[r]["B"])
			if name == "" || !ok {
				continue
			}
			id, err := st.AddDebt(db.DebtInput{Name: name, Initial: amt})
			if err != nil {
				return err
			}
			debtIDs[strings.ToLower(name)] = id
		}
	}

	// --- recurrences
	var recs []finance.Recurrence
	addRec := func(r finance.Recurrence) error {
		id, err := st.SaveRecurrence(r)
		if err != nil {
			return err
		}
		r.ID = id
		recs = append(recs, r)
		return nil
	}
	gf, err := need("Gastos Fixos")
	if err != nil {
		return err
	}
	for r := 5; r < 200; r++ {
		c := gf[r]
		desc, catName := strings.TrimSpace(c["A"]), strings.TrimSpace(c["B"])
		if desc == "" || strings.HasPrefix(desc, "Total") || catName == "" {
			continue
		}
		amt, ok := cents(c["D"])
		if !ok {
			continue
		}
		catID, err := im.cat(finance.Expense, catName)
		if err != nil {
			return err
		}
		start := cur
		if t, ok := excelDate(c["F"]); ok {
			start = finance.MonthOf(t)
		}
		day := 1
		fmt.Sscan(c["C"], &day)
		if err := addRec(finance.Recurrence{
			Kind: finance.Expense, Description: desc, CategoryID: catID, Category: catName, Amount: amt, Payment: legacyRecPayment(catName),
			Day: day, Interval: 1, Start: start, EndMode: finance.EndNever, Active: strings.EqualFold(c["E"], "Sim"),
		}); err != nil {
			return err
		}
	}
	rf, err := need("Receitas Fixas")
	if err != nil {
		return err
	}
	for r := 5; r < 200; r++ {
		c := rf[r]
		src := strings.TrimSpace(c["A"])
		if src == "" || strings.HasPrefix(src, "Total") {
			continue
		}
		amt, ok := cents(c["C"])
		if !ok {
			continue
		}
		catID, err := im.cat(finance.Income, src)
		if err != nil {
			return err
		}
		desc := strings.TrimSpace(c["B"])
		if desc == "" {
			desc = src
		} else {
			desc = src + " · " + desc
		}
		rec := finance.Recurrence{
			Kind: finance.Income, Description: desc, CategoryID: catID, Category: src, Amount: amt,
			Day: 1, Interval: 1, Start: cur, EndMode: finance.EndNever, Active: strings.EqualFold(c["G"], "Sim"),
		}
		fmt.Sscan(c["D"], &rec.Day)
		if t, ok := excelDate(c["E"]); ok {
			rec.Start = finance.MonthOf(t)
		}
		if t, ok := excelDate(c["F"]); ok {
			rec.EndMode, rec.End = finance.EndUntil, finance.MonthOf(t)
		}
		if err := addRec(rec); err != nil {
			return err
		}
	}

	// --- transactions
	var rows []row
	for _, spec := range []struct {
		sheet string
		kind  finance.Kind
	}{{"Receitas", finance.Income}, {"Gastos", finance.Expense}} {
		sh, err := need(spec.sheet)
		if err != nil {
			return err
		}
		for r := 5; r < 5000; r++ {
			c, ok := sh[r]
			if !ok {
				continue
			}
			date, ok1 := excelDate(c["A"])
			amt, ok2 := cents(c["D"])
			catName := strings.TrimSpace(c["C"])
			if !ok1 || !ok2 || amt == 0 || catName == "" {
				continue
			}
			note := strings.TrimSpace(c["E"])
			auto := strings.Contains(note, "automátic")
			if auto {
				note = ""
			}
			rows = append(rows, row{kind: spec.kind, date: date, amount: amt, cat: catName, note: note, auto: auto})
		}
	}
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].date.Before(rows[j].date) })

	linked := finance.MonthSet{}
	var nTx, nDropped, nLinked int
	for _, rw := range rows {
		catID, err := im.cat(rw.kind, rw.cat)
		if err != nil {
			return err
		}
		m := finance.MonthOf(rw.date)
		rec := matchRecurrence(recs, linked, rw, m)
		in := db.TxInput{Kind: rw.kind, Date: rw.date, Amount: rw.amount, CategoryID: catID, Description: rw.note, Source: "import"}
		in.Payment, in.Fixed = legacyPayment(rw.kind, bucketFor(rw.cat))
		if rec != nil {
			// Future rows that just repeat the recurrence are dropped: the projection covers them.
			if rw.date.After(im.today) && rw.amount == rec.Amount && (rw.auto || rw.note == "") {
				linked.Add(rec.ID, m) // still counts as the occurrence for matching purposes
				nDropped++
				continue
			}
			in.RecurrenceID, in.OccMonth = rec.ID, m.String()
			if in.Description == "" {
				in.Description = rec.Description
			}
			linked.Add(rec.ID, m)
			nLinked++
		}
		if rw.kind == finance.Expense {
			low := strings.ToLower(rw.note)
			for name, id := range debtIDs {
				if strings.Contains(low, name) {
					in.DebtID = id
				}
			}
		}
		if _, err := st.InsertTx(in); err != nil {
			return fmt.Errorf("lançamento %s %s: %w", rw.date.Format("2006-01-02"), rw.cat, err)
		}
		nTx++
	}

	// Past months with no matching row didn't happen: skip them so history stays as in the sheet.
	nSkips := 0
	for _, r := range recs {
		for _, m := range r.Months(r.Start, cur.Add(-1)) {
			if !linked.Has(r.ID, m) {
				if err := st.Skip(r.ID, m); err != nil {
					return err
				}
				nSkips++
			}
		}
	}

	fmt.Fprintf(out, "Importado: %d lançamentos (%d ligados a recorrências), %d recorrências, %d dívidas.\n", nTx, nLinked, len(recs), len(debtIDs))
	fmt.Fprintf(out, "%d linhas futuras automáticas descartadas (viraram projeção), %d meses passados sem lançamento marcados como pulados.\n\n", nDropped, nSkips)

	if dash, ok := sheets["Dashboard"]; ok {
		return compare(st, dash, cur, out)
	}
	return nil
}

// matchRecurrence picks the recurrence a row belongs to: same kind and category,
// occurring in that month and not yet taken; exact amount wins, then same day.
func matchRecurrence(recs []finance.Recurrence, linked finance.MonthSet, rw row, m finance.Month) *finance.Recurrence {
	var cands []*finance.Recurrence
	for i := range recs {
		r := &recs[i]
		if r.Kind == rw.kind && r.Category == rw.cat && !linked.Has(r.ID, m) && len(r.Months(m, m)) > 0 {
			cands = append(cands, r)
		}
	}
	if len(cands) == 0 {
		return nil
	}
	for _, r := range cands {
		if r.Amount == rw.amount {
			return r
		}
	}
	for _, r := range cands {
		if r.Day == rw.date.Day() {
			return r
		}
	}
	return cands[0]
}

// compare prints our monthly totals next to the spreadsheet's dashboard for past months.
func compare(st *db.Store, dash Sheet, cur finance.Month, out io.Writer) error {
	type sheetRow struct {
		m                                   finance.Month
		income, card, fixed, total, balance int64
	}
	var srows []sheetRow
	for r := 16; r < 60; r++ {
		t, ok := excelDate(dash[r]["A"])
		if !ok {
			continue
		}
		m := finance.MonthOf(t)
		if m >= cur {
			continue
		}
		var sr sheetRow
		sr.m = m
		sr.income, _ = cents(dash[r]["B"])
		sr.card, _ = cents(dash[r]["C"])
		sr.fixed, _ = cents(dash[r]["D"])
		sr.total, _ = cents(dash[r]["F"])
		sr.balance, _ = cents(dash[r]["G"])
		srows = append(srows, sr)
	}
	if len(srows) == 0 {
		return nil
	}
	from, to := srows[0].m, srows[len(srows)-1].m
	entries, _, err := st.Entries(from, to)
	if err != nil {
		return err
	}
	sums := finance.Summarize(entries, from, to, st.Limits())
	fmt.Fprintln(out, "Conferência com a aba Dashboard (meses passados):")
	fmt.Fprintf(out, "%-9s %14s %14s %14s %14s %14s\n", "mês", "receitas", "cartão", "fixos", "gastos", "sobra")
	bad := 0
	for _, sr := range srows {
		s := sums[sr.m-from]
		mark := func(a, b int64) string {
			if a == b {
				return fmt.Sprintf("%14.2f", float64(a)/100)
			}
			bad++
			return fmt.Sprintf("%7.2f≠%-6.2f", float64(a)/100, float64(b)/100)
		}
		fmt.Fprintf(out, "%-9s %s %s %s %s %s\n", sr.m.Label(), mark(s.Income, sr.income), mark(s.Card, sr.card),
			mark(s.Fixed, sr.fixed), mark(s.Expense, sr.total), mark(s.Balance, sr.balance))
	}
	if bad == 0 {
		fmt.Fprintln(out, "\n✓ Todos os totais batem com a planilha.")
	} else {
		fmt.Fprintf(out, "\n⚠ %d valores divergentes (app≠planilha).\n", bad)
	}
	return nil
}

// legacyRecPayment is the payment method of an expense recurrence in category name.
func legacyRecPayment(name string) finance.PaymentMethod {
	p, _ := legacyPayment(finance.Expense, bucketFor(name))
	return p
}
